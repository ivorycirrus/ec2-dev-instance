#!/usr/bin/env bash
# Builds dist/deploy.sh, a single file that runs without src/.
#
# Copies src/deploy.sh and replaces every function marked "# @embed <file>"
# with one that prints src/<file> from a quoted heredoc. At run time
# dist/deploy.sh writes those contents (CloudFormation template, user data)
# to a temp directory and deploys from there.
#
# Usage: scripts/build.sh   (from any directory)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/src"
OUT="$ROOT/dist/deploy.sh"

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# Matches a line such as:  template()  { cat "$SRC_DIR/x.yaml"; }  # @embed x.yaml
EMBED_RE='^([A-Za-z_][A-Za-z0-9_]*)\(\)[[:space:]]*\{.*#[[:space:]]*@embed[[:space:]]+([^[:space:]]+)[[:space:]]*$'

# File content with a final newline added if it is missing.
content() {
  cat "$1"
  if [[ -n "$(tail -c 1 "$1")" ]]; then echo; fi
}

[[ -f "$SRC/deploy.sh" ]] || die "missing $SRC/deploy.sh"
mkdir -p "$(dirname "$OUT")"
tmp="$(mktemp "$OUT.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

embeds=()   # "function delimiter file" for the check below
lineno=0
while IFS= read -r line || [[ -n "$line" ]]; do
  lineno=$(( lineno + 1 ))
  if [[ "$line" =~ $EMBED_RE ]]; then
    name="${BASH_REMATCH[1]}" file="${BASH_REMATCH[2]}"
    [[ -f "$SRC/$file" ]] || die "src/deploy.sh:$lineno: $name() embeds $file, which is not in src/"
    delim="__EMBED_$(printf '%s' "$name" | tr '[:lower:]' '[:upper:]')__"
    if grep -qxF "$delim" "$SRC/$file"; then
      die "src/$file contains the line $delim, which would end its heredoc early"
    fi
    printf '# Embedded from src/%s by scripts/build.sh.\n' "$file"
    printf '%s() {\n' "$name"
    printf "  cat <<'%s'\n" "$delim"
    content "$SRC/$file"
    printf '%s\n}\n' "$delim"
    embeds+=("$name $delim $file")
  else
    printf '%s\n' "$line"
    if (( lineno == 1 )); then
      echo "# GENERATED by scripts/build.sh from src/. Edit the files in src/ and run scripts/build.sh."
    fi
  fi
done < "$SRC/deploy.sh" > "$tmp"

(( ${#embeds[@]} > 0 )) || die "src/deploy.sh has no '# @embed <file>' functions"
bash -n "$tmp" || die "the built script has a syntax error"

# Each embedded function must print its source file byte for byte.
for entry in "${embeds[@]}"; do
  read -r name delim file <<<"$entry"
  block="$(awk -v start="$name() {" -v delim="$delim" '
    $0 == start { on = 1 }
    on { print }
    on && $0 == delim { getline; print; exit }' "$tmp")"
  if ! cmp -s <(bash -c "$block"$'\n'"$name") <(content "$SRC/$file"); then
    die "$name() in the built script does not reproduce src/$file"
  fi
done

mv "$tmp" "$OUT"
chmod 755 "$OUT"   # mktemp creates the file as 0600

echo "Built ${OUT#"$ROOT"/} ($(( $(wc -c < "$OUT") )) bytes)"
for entry in "${embeds[@]}"; do
  read -r name delim file <<<"$entry"
  echo "  $name() <- src/$file ($(( $(wc -c < "$SRC/$file") )) bytes)"
done
